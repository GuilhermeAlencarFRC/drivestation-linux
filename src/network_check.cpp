#include "udp_robot_link.h"

#include <QCommandLineParser>
#include <QCoreApplication>
#include <QJsonDocument>
#include <QJsonObject>
#include <QNetworkDatagram>
#include <QTextStream>

int main(int argc, char** argv) {
  QCoreApplication app(argc, argv);
  app.setApplicationName(QStringLiteral("drivestation-network-check"));
  app.setApplicationVersion(QStringLiteral(DRIVESTATION_VERSION));
  QCommandLineParser parser;
  parser.setApplicationDescription(
      QStringLiteral("Check experimental DS UDP using a local test peer only."));
  parser.addHelpOption();
  parser.addVersionOption();
  parser.addOption({QStringLiteral("json"), QStringLiteral("Print a machine-readable result.")});
  parser.process(app);

  QUdpSocket peer;
  ds::UdpRobotLink station;
  QString failure;
  bool replying = true;
  bool inputsVerified = false;
  bool observedEnabled = false;
  bool lossDisabled = false;
  bool recoveryDisabled = false;
  bool stopped = false;
  enum class Phase { FirstReply, FirstEnable, Loss, Recovery, SecondEnable, EmergencyStop, Done };
  Phase phase = Phase::FirstReply;
  const auto finish = [&](const QString& error) {
    if (phase == Phase::Done)
      return;
    phase = Phase::Done;
    failure = error;
    app.exit(error.isEmpty() ? 0 : 1);
  };
  QObject::connect(&station, &ds::UdpRobotLink::errorOccurred, &app,
                   [&](const QString& error) { finish(error); });
  QObject::connect(&peer, &QUdpSocket::readyRead, &app, [&] {
    while (peer.hasPendingDatagrams()) {
      const auto datagram = peer.receiveDatagram(ds::wire::MaxDatagram);
      QString error;
      const auto control = ds::wire::decodeControl(datagram.data(), error);
      if (!control) {
        finish(error);
        return;
      }
      // Independent checks on the input values crossing the actual UDP sockets.
      if (control->joysticks.size() != 6 ||
          control->joysticks[0].axes != QVector<qint8>({-128, 0, 127}) ||
          control->joysticks[0].buttons.size() != 10 || !control->joysticks[0].buttons[0] ||
          !control->joysticks[0].buttons[9] ||
          control->joysticks[0].povs != QVector<qint16>({315})) {
        finish(QStringLiteral("Input data did not survive the loopback exchange."));
        return;
      }
      inputsVerified = true;
      if (!replying)
        continue;
      ds::wire::Status status;
      status.sequence = control->sequence;
      status.mode = control->mode;
      status.enabled = control->enabled;
      status.emergencyStopped = control->emergencyStopped;
      status.trace = 0x30;        // Local peer advertises robot code and roboRIO profile.
      status.batteryRaw = 0x0c80; // 12.5 V, generated by this test peer.
      const auto response = ds::wire::encodeStatus(status, error);
      if (!response || peer.writeDatagram(*response, datagram.senderAddress(),
                                          datagram.senderPort()) != response->size()) {
        finish(error.isEmpty() ? peer.errorString() : error);
        return;
      }
    }
  });
  QObject::connect(&station, &ds::UdpRobotLink::changed, &app, [&] {
    const auto& state = station.connection();
    const auto& status = state.status();
    if (status && status->voltage() != 12.5) {
      finish(QStringLiteral("Loopback battery voltage was not decoded as 12.5 V."));
      return;
    }
    switch (phase) {
    case Phase::FirstReply:
      if (status && !status->enabled) {
        phase = Phase::FirstEnable;
        if (!station.requestEnable())
          finish(QStringLiteral("Initial explicit enable was rejected."));
      }
      break;
    case Phase::FirstEnable:
      if (status && status->enabled) {
        observedEnabled = true;
        phase = Phase::Loss;
        replying = false;
      }
      break;
    case Phase::Loss:
      if (!state.connected() && !state.enableRequested()) {
        lossDisabled = true;
        phase = Phase::Recovery;
        replying = true;
      }
      break;
    case Phase::Recovery:
      if (status) {
        recoveryDisabled = !status->enabled && !state.enableRequested();
        if (!recoveryDisabled) {
          finish(QStringLiteral("Recovery implicitly enabled the session."));
          break;
        }
        phase = Phase::SecondEnable;
        if (!station.requestEnable())
          finish(QStringLiteral("Enable after recovery was rejected."));
      }
      break;
    case Phase::SecondEnable:
      if (status && status->enabled) {
        phase = Phase::EmergencyStop;
        station.emergencyStop();
      }
      break;
    case Phase::EmergencyStop:
      if (status && status->emergencyStopped && !status->enabled && !state.enableRequested()) {
        stopped = state.emergencyStopped();
        finish(stopped ? QString() : QStringLiteral("Emergency stop was not latched."));
      }
      break;
    case Phase::Done:
      break;
    }
  });

  if (!peer.bind(QHostAddress::LocalHost, 0, QUdpSocket::DontShareAddress)) {
    failure = peer.errorString();
  } else {
    QVector<ds::wire::Joystick> joysticks(6);
    joysticks[0].axes = {-128, 0, 127};
    joysticks[0].buttons.resize(10);
    joysticks[0].buttons[0] = joysticks[0].buttons[9] = true;
    joysticks[0].povs = {315};
    if (!station.setJoysticks(joysticks) ||
        !station.start(QHostAddress::LocalHost, peer.localPort(), 0, QHostAddress::LocalHost)) {
      failure = station.lastError();
    } else {
      QTimer::singleShot(5000, &app, [&] { finish(QStringLiteral("Loopback check timed out.")); });
      app.exec();
    }
  }
  const bool success = failure.isEmpty() && inputsVerified && observedEnabled && lossDisabled &&
                       recoveryDisabled && stopped;
  QJsonObject result{{"success", success},
                     {"version", app.applicationVersion()},
                     {"scope", "IPv4 loopback; no physical robot"},
                     {"inputs_verified", inputsVerified},
                     {"enabled_observed", observedEnabled},
                     {"timeout_disabled", lossDisabled},
                     {"reconnected_disabled", recoveryDisabled},
                     {"estop_latched", stopped},
                     {"sent", static_cast<qint64>(station.sentCount())},
                     {"received", static_cast<qint64>(station.receivedCount())},
                     {"rejected", static_cast<qint64>(station.rejectedCount())},
                     {"error", failure}};
  // Prevent stop/destruction notifications from restarting the scenario.
  phase = Phase::Done;
  station.stop();
  QTextStream output(stdout);
  if (parser.isSet(QStringLiteral("json")))
    output << QJsonDocument(result).toJson(QJsonDocument::Compact) << '\n';
  else
    output << (success ? "PASS" : "FAIL")
           << ": UDP loopback, inputs, explicit enable, timeout, disabled recovery and E-Stop.\n"
           << (failure.isEmpty() ? QString() : failure + '\n');
  return success ? 0 : 1;
}
